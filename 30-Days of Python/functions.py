# Function without Parameters
def generate_full_name():
    first_name='Sneha'
    last_name='Nair'
    space=' '
    full_name=first_name + space+last_name
    print(full_name)
generate_full_name()

def add_two_numbers():
    num1=10
    num2=20
    total=num1+num2
    print(total)
add_two_numbers()

# Function Returning a Value 
def generate_full_name2():
    first_name='Sneha'
    last_name='Nair'
    space=' '
    full_name=first_name+space+last_name
    return full_name
print(generate_full_name2())


def add_two_numbers2():
    num1=10
    num2=50
    total=num1+num2
    return total
print(add_two_numbers2())

